class SalarioEmpleado:

    @staticmethod
    def calcular_salario_bruto(horas: float, valor_hora: float) -> float:
        return horas * valor_hora

    @staticmethod
    def calcular_retencion(salario_bruto: float, porcentaje_retencion: float) -> float:
        return salario_bruto * (porcentaje_retencion / 100)

    @staticmethod
    def calcular_salario_neto(salario_bruto: float, retencion: float) -> float:
        return salario_bruto - retencion


def main():
    horas = 48.0
    valor_hora = 5000.0
    porcentaje_retencion = 12.5
    salario_bruto = SalarioEmpleado.calcular_salario_bruto(horas, valor_hora)
    retencion = SalarioEmpleado.calcular_retencion(salario_bruto, porcentaje_retencion)
    salario_neto = SalarioEmpleado.calcular_salario_neto(salario_bruto, retencion)
    print("=== LIQUIDACIÓN DEL EMPLEADO ===")
    print(f"Salario Bruto: ${salario_bruto:,.2f}")
    print(f"Retención en la Fuente ({porcentaje_retencion}%): ${retencion:,.2f}")
    print(f"Salario Neto: ${salario_neto:,.2f}")


if __name__ == "__main__":
    main()

