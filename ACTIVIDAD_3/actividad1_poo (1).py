class OperacionesCirculo:

  @staticmethod
  def Calcular_area(radio: float) -> float:
    return math.pi * (radio ** 2)

  @staticmethod
  def Calcular_circunferencia(radio: float) -> float:
    return 2 * math.pi * radio

def main():
  radio = float(input(f"Ingrese el valor del radio del circulo: "))
  area = OperacionesCirculo.Calcular_area(radio)
  circunferencia = OperacionesCirculo.Calcular_circunferencia(radio)
  print("==RESULTADOS==")
  print(f"El Area del circulo es {area:,.2f}")
  print(f"La Circunferencia del circulo es {circunferencia:,.2f}")

if __name__ == "__main__":
  main()